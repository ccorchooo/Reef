#!/usr/bin/env python3
"""Generate reef/theme/Tokens.qml, reef/theme/ColorRoles.qml and hypr/tokens.lua from design/tokens.json.

Usage: python3 reef/scripts/gen-tokens.py   (from anywhere)

Never edit the generated files by hand: change design/tokens.json and re-run.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "design" / "tokens.json"
QML_OUT = ROOT / "reef" / "theme" / "Tokens.qml"
ROLES_OUT = ROOT / "reef" / "theme" / "ColorRoles.qml"
LUA_OUT = ROOT / "hypr" / "tokens.lua"

HEADER = "GENERATED by reef/scripts/gen-tokens.py from design/tokens.json. Do not edit."


def camel(name: str) -> str:
    """space-2-5 -> space2_5, radius-lg -> radiusLg"""
    head, *rest = re.split(r"[-_ ]", name)
    out = head
    for p in rest:
        out += ("_" if out[-1].isdigit() and p[:1].isdigit() else "") + p[:1].upper() + p[1:]
    return out


def num(v):
    """'16px' -> 16, '20ms' -> 20, 0.5 -> 0.5"""
    if isinstance(v, (int, float)):
        return v
    m = re.fullmatch(r"(-?[\d.]+)(px|ms)?", str(v).strip())
    if not m:
        raise ValueError(f"not a number: {v!r}")
    f = float(m.group(1))
    return int(f) if f.is_integer() else f


def qcolor(v: str) -> str:
    """CSS color -> QML color string (#RRGGBB or #AARRGGBB)."""
    v = v.strip()
    if v.startswith("#"):
        return v.lower()
    m = re.fullmatch(r"rgba?\(([^)]*)\)", v)
    if not m:
        raise ValueError(f"unsupported color: {v!r}")
    parts = [p.strip() for p in m.group(1).split(",")]
    r, g, b = (int(p) for p in parts[:3])
    a = float(parts[3]) if len(parts) > 3 else 1.0
    return "#{:02x}{:02x}{:02x}{:02x}".format(round(a * 255), r, g, b)


def shadow(v: str) -> dict:
    m = re.fullmatch(r"(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(\d+)(?:px)?\s+(.+)", v.strip())
    if not m:
        raise ValueError(f"unsupported shadow: {v!r}")
    return {"x": int(m.group(1)), "y": int(m.group(2)), "blur": int(m.group(3)), "color": qcolor(m.group(4))}


def family(css: str) -> str:
    return css.split(",")[0].strip().strip('"')


def js(v) -> str:
    return json.dumps(v, ensure_ascii=False)


def main():
    t = json.loads(SRC.read_text())
    L = []
    w = L.append

    w(f"// {HEADER}")
    w("pragma Singleton")
    w("import QtQuick")
    w("import Quickshell")
    w("import qs.services")
    w("")
    w("Singleton {")
    w("    id: root")
    w("")
    w("    // Scale multipliers from Settings → Scale, times the shell-wide zoom (Settings →")
    w("    // Accessibility → Zoom). Spacing, radius, type and pixel sizes below already include")
    w("    // them; the raw* values don't. Ratios and angles never zoom.")
    w("    readonly property real zoom: Math.max(0.5, Config.options.scale.zoom)")
    w("    readonly property real spacingScale: Config.options.scale.spacing * zoom")
    w("    readonly property real cornerScale: Config.options.scale.corners * zoom")
    w("    readonly property real textScale: Config.options.scale.text * zoom")
    w("")

    # spacing
    w("    // Spacing (4px grid)")
    for tok in t["spacing"]["tokens"]:
        n, v = camel(tok["name"]), num(tok["value"])
        w(f"    readonly property real raw{n[0].upper() + n[1:]}: {v}")
        w(f"    readonly property real {n}: {v} * spacingScale")
    w("")

    # radius
    w("    // Corner radius (M3 scale; concentric rule: inner = outer - padding)")
    for tok in t["radius"]["tokens"]:
        n, v = camel(tok["name"]), num(tok["value"])
        w(f"    readonly property real raw{n[0].upper() + n[1:]}: {v}")
        w(f"    readonly property real {n}: {v} * cornerScale")
    w("")

    # size
    w("    // Fixed sizes for shell chrome (pixel sizes follow the zoom)")
    for tok in t["size"]["tokens"]:
        px = str(tok["value"]).strip().endswith("px")
        w(f"    readonly property real {camel(tok['name'])}: {num(tok['value'])}" + (" * zoom" if px else ""))
    w("")

    # type
    fams = {k: family(v) for k, v in t["type"]["families"].items()}
    w("    // Type")
    w(f"    readonly property var fontFamilies: ({js(fams)})")
    styles = {}
    for g in t["type"]["groups"]:
        for s in g["styles"]:
            styles[camel(s["name"])] = {
                "family": g["family"],
                "size": num(s["fontSize"]),
                "lineHeight": num(s["lineHeight"]),
                "weight": s["fontWeight"],
                "letterSpacing": num(s.get("letterSpacing", 0)),
                "emphasized": s["name"].endswith("-emphasized"),
                "sample": s.get("sample", ""),
            }
    w("    readonly property var typeStyles: ({")
    w(",\n".join(f"        {js(k)}: {js(v)}" for k, v in styles.items()))
    w("    })")
    w("")

    # colors
    themes = [th["id"] for th in t["color"]["themes"]]
    w("    // Reference color schemes (seed " + t["meta"]["seed"] + "). Colors.qml uses these with no wallpaper.")
    w(f"    readonly property string seed: {js(t['meta']['seed'])}")
    w(f"    readonly property var themeIds: {js(themes)}")
    w("    readonly property var referenceSchemes: ({")
    blocks = []
    for th in themes:
        roles = {camel(tok["name"]): qcolor(tok["value"][th]) for tok in t["color"]["tokens"]}
        body = ",\n".join(f"            {js(k)}: {js(v)}" for k, v in roles.items())
        blocks.append(f"        {js(th)}: {{\n{body}\n        }}")
    w(",\n".join(blocks))
    w("    })")
    w("    // Roles that never change with the wallpaper (the Island family).")
    fixed = [camel(tok["name"]) for tok in t["color"]["tokens"]
             if tok["name"].startswith("island") or tok["name"].startswith("on-island") or tok["name"].startswith("scrim") or tok["name"] == "screen-corner"]
    w(f"    readonly property var fixedRoles: {js(fixed)}")
    # Classic palettes (Settings → Look → Palette): base colors per mode; schemegen.js
    # derives the rest.
    pals = {p["id"]: {"name": p["name"], "dark": p["dark"], "light": p["light"]} for p in t["color"].get("palettes", [])}
    w("    // Classic palettes: { id: { name, dark: { surface, …, primary, secondary, tertiary, error }, light } }")
    w("    readonly property var palettes: ({")
    w(",\n".join(f"        {js(k)}: {js(v)}" for k, v in pals.items()))
    w("    })")
    w(f"    readonly property var paletteIds: {js(list(pals.keys()))}")
    w("")

    # shadows
    w("    // Shadows per theme: {x, y, blur, color}")
    sh = {camel(tok["name"]): {th: shadow(tok["value"][th]) for th in themes} for tok in t["shadow"]["tokens"]}
    w(f"    readonly property var shadows: ({js(sh)})")
    w("")

    # opacity
    w("    // Opacity (state layers, disabled)")
    for tok in t.get("opacity", {}).get("tokens", []):
        w(f"    readonly property real {camel(tok['name'])}Opacity: {num(tok['value'])}")
    w("")

    # motion
    m = t["motion"]
    springs = {camel(k): {kk: vv for kk, vv in v.items() if kk != "usage"} for k, v in m["springs"].items()}
    w("    // Motion (MOTION.md). Use through the Motion singleton, never directly.")
    w(f"    readonly property var springs: ({js(springs)})")
    for tok in m["tokens"]:
        w(f"    readonly property real {camel(tok['name'])}: {num(tok['value'])}")
    w("}")

    QML_OUT.write_text("\n".join(L) + "\n")

    # Color role properties: the base type of the Colors singleton.
    # QML treats `onSomething` as a signal handler, so "on-*" roles live under `on`:
    # on-surface -> Colors.on.surface, on-primary-container -> Colors.on.primaryContainer.
    R = [f"// {HEADER}", "import QtQuick", "import Quickshell", "",
         "// One color property per role in tokens.json. Colors.qml fills `roles`.",
         "// \"on-*\" roles are under `on` (Colors.on.surface) because QML reserves on<Name>.",
         "Singleton {", "    id: root", "    property var roles: ({})"]
    on_roles = []
    for tok in t["color"]["tokens"]:
        n = camel(tok["name"])
        if tok["name"].startswith("on-"):
            on_roles.append((camel(tok["name"][3:]), n))
            continue
        R.append(f"    readonly property color {n}: roles.{n} ?? \"transparent\"")
    R.append("    readonly property QtObject on: QtObject {")
    for short, n in on_roles:
        R.append(f"        readonly property color {short}: root.roles.{n} ?? \"transparent\"")
    R.append("    }")
    R.append("}")
    ROLES_OUT.write_text("\n".join(R) + "\n")

    # Hyprland
    sp = {tok["name"]: num(tok["value"]) for tok in t["spacing"]["tokens"]}
    rd = {tok["name"]: num(tok["value"]) for tok in t["radius"]["tokens"]}
    sz = {tok["name"]: num(tok["value"]) for tok in t["size"]["tokens"]}
    lua = [f"-- {HEADER}", "return {"]
    lua += [f'    ["{k}"] = {v},' for k, v in {**sp, **rd}.items()]
    lua += [
        f"    gaps_in  = {sp['space-2']},  -- space-2",
        f"    gaps_out = {sp['space-4']}, -- space-4",
        f"    rounding = {rd['radius-lg']}, -- radius-lg",
        "    -- M3E springs (MOTION.md): stiffness and the damping *ratio* (1 = no bounce).",
        "    -- Hyprland's spring curves take a damping coefficient: 2 * ratio * sqrt(stiffness).",
        "    -- duration (ms) and bezier are MOTION.md's fallback curve for each.",
        "    springs = {",
    ]
    for k, v in t["motion"]["springs"].items():
        b = ", ".join(str(x) for x in v["bezier"])
        lua.append(f'        ["{k}"] = {{ stiffness = {num(v["stiffness"])}, damping = {num(v["damping"])}, '
                   f'duration = {num(v["duration"])}, bezier = {{ {b} }} }},')
    lua += ["    },"]
    # The reference scheme (no wallpaper yet), "rrggbb" per role, for Hyprland's colors.
    lua.append("    -- The reference scheme (tokens.json), used before Reef has made one from a wallpaper.")
    lua.append("    scheme = {")
    for mode in ("dark", "light"):
        lua.append(f"        {mode} = {{")
        for tok in t["color"]["tokens"]:
            v = tok["value"]
            v = v.get(mode) if isinstance(v, dict) else v
            if isinstance(v, str) and v.startswith("#") and len(v) == 7:
                lua.append(f'            {camel(tok["name"])} = "{v[1:].lower()}",')
        lua.append("        },")
    lua += ["    },", "}"]
    LUA_OUT.write_text("\n".join(lua) + "\n")
    for p in (QML_OUT, ROLES_OUT, LUA_OUT):
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
